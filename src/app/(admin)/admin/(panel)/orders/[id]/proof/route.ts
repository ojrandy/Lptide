import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { sqlite } from "@/db";
import { requireAdmin } from "@/lib/auth";
import { privateDir } from "@/lib/uploads";

// GET /admin/orders/{id}/proof/ — the order's proof of payment (docs/10 V9). Admin only; never cached.
const TYPES: Record<string, string> = { jpg: "image/jpeg", png: "image/png", webp: "image/webp", pdf: "application/pdf" };

export async function GET(_req: Request, ctx: RouteContext<"/admin/orders/[id]/proof">) {
  await requireAdmin();
  const id = Number((await ctx.params).id);
  const row = Number.isInteger(id) ? (sqlite.prepare("SELECT paymentProof FROM orders WHERE id = ?").get(id) as { paymentProof: string | null } | undefined) : undefined;
  const name = row?.paymentProof;
  // Names are generated by saveUpload (32 hex + extension); anything else is refused.
  const m = name?.match(/^[a-f0-9]{32}\.(jpg|png|webp|pdf)$/);
  if (!name || !m) return new Response("Not found", { status: 404 });
  try {
    const buf = await readFile(join(/*turbopackIgnore: true*/ privateDir(), "payment-proofs", name));
    return new Response(new Uint8Array(buf), {
      headers: {
        "Content-Type": TYPES[m[1]],
        "Cache-Control": "private, no-store",
        "X-Content-Type-Options": "nosniff",
        "Content-Disposition": `inline; filename="order-${id}-proof.${m[1]}"`,
      },
    });
  } catch {
    return new Response("Not found", { status: 404 });
  }
}
